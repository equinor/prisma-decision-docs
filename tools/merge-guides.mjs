#!/usr/bin/env node
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { guides } from './guides.mjs';
import { pages } from './pages.mjs';

const workflow = fileURLToPath(new URL('../workflow/', import.meta.url));
const check = process.argv.includes('--check');
const filename = guide => guide.file ?? `${guide.page}.md`;
const rendered = [];

for (const [index, guide] of guides.entries()) {
	const page = pages.find(page => page.folder === guide.page);
	if (!page) throw new Error(`Unknown guide page: ${guide.page}`);
	const figureFolder = page.figureFolder ?? page.folder;
	const source = path.join(workflow, 'figures', figureFolder);
	const selected = guide.sections.flatMap(section => section.figures);
	if (new Set(selected).size !== selected.length) throw new Error(`Duplicate figure in guide: ${guide.page}`);
	const available = (await readdir(source)).filter(file => file.endsWith('.md')).map(file => file.slice(0, -3));
	const missing = available.filter(name => !selected.includes(name));
	if (missing.length) throw new Error(`Unmerged figures in ${guide.page}: ${missing.join(', ')}`);

	const navigation = [
		index > 0 ? `[Previous: ${guides[index - 1].title}](./${filename(guides[index - 1])})` : null,
		'[Workflow](./README.md)',
		index < guides.length - 1 ? `[Next: ${guides[index + 1].title}](./${filename(guides[index + 1])})` : null,
	].filter(Boolean).join(' | ');
	const parts = [
		'<!-- Generated by node tools/merge-guides.mjs. Edit tools/guides.mjs and the figure Markdown sources. -->',
		`# ${guide.title}`,
		navigation,
		guide.intro,
	];
	for (const section of guide.sections) {
		parts.push(`## ${section.title}`);
		for (const name of section.figures) {
			const fragment = await readFile(path.join(source, `${name}.md`), 'utf8');
			parts.push(fragment.trim()
				.replace(/^## (.+)\n\n/, (_, title) =>
					section.figures.length === 1 || title === section.title ? '' : `### ${title}\n\n`)
				.replace(/!\[([^\]]*)\]\(<\.\/([^>]+)>\)/g, `![$1](<./figures/${figureFolder}/$2>)`));
		}
	}
	parts.push(navigation);
	rendered.push({ file: path.join(workflow, filename(guide)), content: `${parts.join('\n\n')}\n` });
}

for (const { file, content } of rendered) {
	if (check) {
		if (await readFile(file, 'utf8') !== content) throw new Error(`Stale guide: ${file}. Run node tools/merge-guides.mjs`);
	} else {
		await writeFile(file, content);
	}
}
console.log(`${check ? 'Checked' : 'Merged'} ${rendered.length} page guides.`);
